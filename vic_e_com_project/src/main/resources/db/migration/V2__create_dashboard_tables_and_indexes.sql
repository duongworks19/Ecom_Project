CREATE TABLE IF NOT EXISTS vendors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT UNIQUE REFERENCES users(id),
    approval_status VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_code VARCHAR(30) UNIQUE,
    customer_id BIGINT,
    shop_id BIGINT,
    status VARCHAR(20) NOT NULL,
    total_amount NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    delivered_at TIMESTAMP NULL
);

CREATE TABLE IF NOT EXISTS order_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES orders(id),
    from_status VARCHAR(20),
    to_status VARCHAR(20),
    changed_by BIGINT,
    changed_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS shipments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES orders(id),
    shipper_id BIGINT,
    status VARCHAR(20),
    assigned_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS delivery_failures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT REFERENCES shipments(id),
    reason VARCHAR(500),
    attempt_no INT,
    next_action VARCHAR(20) NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS return_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id BIGINT,
    customer_id BIGINT,
    status VARCHAR(20),
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status);
CREATE INDEX IF NOT EXISTS idx_orders_delivered_at ON orders(delivered_at);
CREATE INDEX IF NOT EXISTS idx_vendors_approval_status ON vendors(approval_status);
CREATE INDEX IF NOT EXISTS idx_delivery_failures_next_action ON delivery_failures(next_action);
CREATE INDEX IF NOT EXISTS idx_return_requests_status ON return_requests(status);
CREATE INDEX IF NOT EXISTS idx_shipments_order_id_status ON shipments(order_id, status);
